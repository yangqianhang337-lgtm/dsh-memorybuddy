/**
 * The empty skeletons every file starts as.
 *
 * HARD RULE (memory-plan §4): no template may carry real remembered content.
 * The screenshots that specified this plugin's layout showed a university, a
 * skill pack and an editor path — those are FORMAT references for the human
 * reading the plan, not defaults, and writing them into a shipped template
 * would hand every new user someone else's memories. Every body below is
 * therefore either the plan's own mandated default (the persona sentence) or a
 * placeholder that says the file is empty.
 */

import { renderDocument } from './document.ts'
import { TOPICS } from '../protocol.ts'

/** The default persona body, mandated verbatim by memory-plan §4. */
export const DEFAULT_PERSONA_BODY = '你是 DSH同学，我最好的助手。'

/** Default values of every preference field (memory-plan §4). */
export const DEFAULT_PREFERENCES = {
  userName: '',
  agentName: 'DSH同学',
  replyStyle: '默认',
  welcome: true,
  showFileChanges: false,
  conversationMemory: true,
  localMemorySkills: true,
  consolidateOn: 'startup-idle',
  consolidateIntervalHours: 24,
  consolidateIdleMinutes: 10,
  consolidateFixedTime: '03:00',
  consolidateQuiet: true,
  modelPolicy: 'free-first',
  modelAllowlist: [] as string[],
  promptBudgetBytes: 4096,
} as const

/** `preferences.md`. */
export function preferencesTemplate(now: string): string {
  return renderDocument(
    {
      kind: 'preferences',
      schema: 1,
      updated: now,
      userName: DEFAULT_PREFERENCES.userName,
      agentName: DEFAULT_PREFERENCES.agentName,
      replyStyle: DEFAULT_PREFERENCES.replyStyle,
      welcome: DEFAULT_PREFERENCES.welcome,
      showFileChanges: DEFAULT_PREFERENCES.showFileChanges,
      conversationMemory: DEFAULT_PREFERENCES.conversationMemory,
      localMemorySkills: DEFAULT_PREFERENCES.localMemorySkills,
      consolidateOn: DEFAULT_PREFERENCES.consolidateOn,
      consolidateIntervalHours: DEFAULT_PREFERENCES.consolidateIntervalHours,
      consolidateIdleMinutes: DEFAULT_PREFERENCES.consolidateIdleMinutes,
      consolidateFixedTime: DEFAULT_PREFERENCES.consolidateFixedTime,
      consolidateQuiet: DEFAULT_PREFERENCES.consolidateQuiet,
      modelPolicy: DEFAULT_PREFERENCES.modelPolicy,
      modelAllowlist: [...DEFAULT_PREFERENCES.modelAllowlist],
      promptBudgetBytes: DEFAULT_PREFERENCES.promptBudgetBytes,
    },
    [
      '# 个性化',
      '',
      '这个文件保存你的称呼、助手的名字与回复风格。面板上的改动会写回这里，',
      '你也可以直接用编辑器改：改完保存，面板下一次刷新就会读到新值。',
    ].join('\n'),
  )
}

/** `profile.md` — the persona. */
export function profileTemplate(now: string): string {
  return renderDocument(
    { kind: 'persona', schema: 1, updated: now, injectOrder: 100 },
    DEFAULT_PERSONA_BODY,
  )
}

/** `instructions.md`. */
export function instructionsTemplate(now: string): string {
  return renderDocument(
    { kind: 'instructions', schema: 1, updated: now },
    [
      '# 指令',
      '',
      '写在这里的要求会被注入每次对话的系统提示，优先级高于自动积累的记忆。',
      '（当前为空：还没有写下任何长期指令。）',
    ].join('\n'),
  )
}

/** The four index sections, in the order memory-plan §4.5 fixes. */
export const INDEX_SECTIONS = [
  { key: 'background', title: '工作背景' },
  { key: 'habits', title: '行事风格' },
  { key: 'environment', title: '本机软件与路径（跨项目）' },
  { key: 'projects', title: '项目索引' },
] as const

/** The placeholder of a section nothing has been learned for yet. */
export const INDEX_PLACEHOLDER = '<!-- 由插件从真实会话中积累；暂无内容 -->'

/** `memory/index.md` — regenerated by consolidation, never hand-authored. */
export function memoryIndexTemplate(now: string): string {
  return renderDocument(
    {
      kind: 'memory-index',
      schema: 1,
      generated: now,
      sources: ['habits', 'background', 'environment', 'preferences-learned'],
      budgetBytes: DEFAULT_PREFERENCES.promptBudgetBytes,
    },
    [
      '# 长期记忆',
      '',
      ...INDEX_SECTIONS.flatMap(section => [`## ${section.title}`, INDEX_PLACEHOLDER, '']),
    ]
      .join('\n')
      .trimEnd(),
  )
}

/** `memory/<topic>.md` — one per topic, entries appended below the heading. */
export function topicTemplate(topic: string, title: string, now: string): string {
  return renderDocument(
    { kind: 'memory-topic', topic, title, schema: 1, updated: now },
    [`# ${title}`, '', '（当前为空。）'].join('\n'),
  )
}

/**
 * `sessions/<date>/<id>.md` — the empty note a session starts as.
 *
 * The collector rewrites this file as the session runs; the skeleton exists so
 * a note is never missing entirely (a crash mid-session still leaves the
 * session id, its workspace and its start time behind).
 */
export function sessionNoteTemplate(now: string): string {
  return renderDocument(
    { kind: 'session-note', schema: 1, consolidated: false, updated: now },
    [
      '## 做了什么',
      '',
      '## 观察到的工作习惯候选',
      '',
      '## 项目相关',
      '',
      '## 未决事项',
      '',
    ].join('\n'),
  )
}

/** Every skeleton, keyed by its path relative to the data root. */
export function initialFiles(now: string): Record<string, string> {
  const files: Record<string, string> = {
    'preferences.md': preferencesTemplate(now),
    'profile.md': profileTemplate(now),
    'instructions.md': instructionsTemplate(now),
    'memory/index.md': memoryIndexTemplate(now),
  }
  for (const topic of TOPICS) {
    files[`memory/${topic.file}`] = topicTemplate(topic.key, topic.title, now)
  }
  return files
}
